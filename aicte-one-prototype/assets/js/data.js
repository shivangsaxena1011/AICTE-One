// Local in-browser reactive state manager with persistence
class LocalStore {
  constructor() {
    this.key = "aicte_one_governance_db_v2";
    this.db = this.load();
  }

  load() {
    try {
      const stored = localStorage.getItem(this.key);
      if (stored) {
        return JSON.parse(stored);
      }
    } catch (e) {
      console.warn("Could not read localStorage:", e);
    }
    return JSON.parse(JSON.stringify(SEED_DATA));
  }

  save() {
    try {
      localStorage.setItem(this.key, JSON.stringify(this.db));
    } catch (e) {
      console.warn("Could not write to localStorage:", e);
    }
  }

  reset() {
    this.db = JSON.parse(JSON.stringify(SEED_DATA));
    this.save();
  }

  resetToDefaults() {
    this.reset();
  }

  log(actor, role, action, entity_type, record, detail) {
    const timeStr = new Date().toISOString().replace('T', ' ').slice(0, 19);
    const entry = {
      id: "AUD-" + Date.now().toString().slice(-6),
      time: timeStr,
      actor: actor || "Officer",
      role: role || "Central Administration",
      action: action,
      entity_type: entity_type || "System",
      record: record || "—",
      detail: detail || ""
    };
    this.db.audit.unshift(entry);
    if (this.db.audit.length > 300) this.db.audit.pop();
    this.save();
  }
}

const localStore = new LocalStore();
window.localStore = localStore;
window.DataStore = localStore;

// Standard Universal UI & Format Helpers
function escapeHtml(s = "") {
  return String(s || "").replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
window.escapeHtml = escapeHtml;

function formatDate(s) {
  if (!s) return "—";
  try {
    const d = new Date(s.includes("T") ? s : s + "T12:00:00");
    if (isNaN(d.getTime())) return s;
    return d.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
  } catch (e) {
    return s;
  }
}
window.formatDate = formatDate;

function renderPill(s) {
  const x = (s || "").toLowerCase();
  let c = "gray";
  if (/verified|compliant|on track|active|satisfied|closed|disposed|approved/i.test(x)) c = "green";
  else if (/overdue|mismatch|at risk|expired|anomal|action required|deficienc|rejected/i.test(x)) c = "red";
  else if (/due soon|pending|review|clarification|attention|awaiting|expiry|in review|scrutiny/i.test(x)) c = "amber";
  else if (/demo/i.test(x)) c = "purple";
  else if (/assigned|process|scheduling|evc/i.test(x)) c = "blue";
  return `<span class="pill ${c}">${escapeHtml(s)}</span>`;
}
window.renderPill = renderPill;
